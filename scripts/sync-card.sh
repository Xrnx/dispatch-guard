#!/usr/bin/env bash
# Regenerate hooks/orchestrator-card.ts from an orchestrator SKILL.md.
# Usage: scripts/sync-card.sh <path/to/orchestrator/SKILL.md>
# Needs: sha256sum, and node or python3. CARD is the file verbatim (JSON string literal); SECTIONS maps each
# sibling *.md (the core's on-demand sections) to its text, the fallback when a section file is missing.
set -euo pipefail
src="${1:?usage: scripts/sync-card.sh <SKILL.md>}"
[ -f "$src" ] || { echo "no such file: $src" >&2; exit 1; }
out="$(cd "$(dirname "$0")/.." && pwd)/hooks/orchestrator-card.ts"
hash="$(sha256sum "$src" | cut -c1-8)"
if command -v node >/dev/null 2>&1; then
  lit="$(node -e 'process.stdout.write(JSON.stringify(require("fs").readFileSync(process.argv[1], "utf8")))' "$src")"
  sec="$(node -e 'const fs=require("fs"),p=require("path"),d=p.dirname(process.argv[1]),o={};for(const f of fs.readdirSync(d).sort())if(f.endsWith(".md")&&f!=="SKILL.md")o[f]=fs.readFileSync(p.join(d,f),"utf8");process.stdout.write(JSON.stringify(o))' "$src")"
elif command -v python3 >/dev/null 2>&1; then
  lit="$(python3 -I -c 'import json,sys; sys.stdout.write(json.dumps(open(sys.argv[1], encoding="utf-8", newline="").read(), ensure_ascii=False))' "$src")"
  sec="$(python3 -I -c 'import json,os,sys; d=os.path.dirname(os.path.abspath(sys.argv[1])); sys.stdout.write(json.dumps({f: open(os.path.join(d,f), encoding="utf-8", newline="").read() for f in sorted(os.listdir(d)) if f.endswith(".md") and f!="SKILL.md"}, ensure_ascii=False))' "$src")"
else
  echo "need node or python3" >&2; exit 1
fi
{
  echo "// Generated by scripts/sync-card.sh from the orchestrator SKILL.md — do not edit by hand."
  echo "export const CARD_HASH = '$hash'"
  printf 'export const CARD: string = %s\n' "$lit"
  printf 'export const SECTIONS: Record<string, string> = %s\n' "$sec"
} > "$out"
echo "wrote $out (hash $hash)"
